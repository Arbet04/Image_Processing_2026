"""
Queue Manager — ต่อคิวงานสร้างรูปด้วย asyncio.Semaphore
============================================================
ทำไมต้องมีไฟล์นี้: GPU เครื่องเรารับงานสร้างรูปได้ทีละ 1 งานเท่านั้น ถ้าปล่อยให้
หลาย request ยิงไปหา Forge Neo พร้อมกันตรงๆ (ไม่ผ่านไฟล์นี้) อาจชนกันหรือทำให้
Forge Neo error ได้ ไฟล์นี้ทำหน้าที่บังคับให้ทุกงานต้อง "รอคิว" ก่อนเริ่มทำงานจริง

หลักการทำงาน (เข้าใจง่ายๆ): Semaphore(1) เหมือนกุญแจห้องน้ำที่มีอยู่ใบเดียว
คนแรกที่มาถึงหยิบกุญแจไปเข้าห้องน้ำ (เริ่ม generate) คนที่มาทีหลังต้องยืนรอ
หน้าห้องจนกว่าคนแรกจะออกมาคืนกุญแจ (generate เสร็จ) ถึงจะเข้าไปทำต่อได้

จำกัดความยาวคิว: ยอมให้รอได้ไม่เกิน MAX_QUEUE_SIZE งาน (ตั้งใน .env, default 3)
ถ้าเกินจะโยน QueueFullError ทันที (main.py ตอบ 503) แทนการให้ client รอจนหมดเวลา
"""

# ─────────────────────────────────────────────────────────────────────────────
# เส้นทางคำขอใน AI Service: Backend ส่ง POST /generate (JSON) มาที่ port 8001 ผ่าน 5 ขั้นก่อนถึง GPU
#   [1] Uvicorn :8001      เปิด port รับ HTTP จาก Backend (รันด้วย uvicorn main:app --host 0.0.0.0)
#   [2] main.py            FastAPI จับคู่ POST /generate กับฟังก์ชัน generate()
#   [3] models.py          Pydantic ตรวจข้อมูล ผิดตอบ 422 ทันที
#   [4] queue_manager.py   เช็คคิวเต็ม รอถึงตา (เจนทีละรูป FIFO)
#   [5] forge_client.py    httpx ส่งไป Forge Neo /sdapi/v1/txt2img
#   แล้ว Forge Neo (port 7860) ใช้ GPU เจนรูป ตอบกลับเป็น base64 ย้อนทางเดิม [5] → [4] → [2] → Backend
#
# จุดที่คำขอถูกหยุดก่อนถึง GPU:  [หยุด] 422 ข้อมูลผิด · [หยุด] 503 คิวเต็ม · [หยุด] 503 ต่อ Forge ไม่ได้
# ─────────────────────────────────────────────────────────────────────────────
# ไฟล์นี้:    ขั้น [4] — ต่อคิว ให้เจนทีละรูปตามลำดับที่มาถึง (FIFO) และปฏิเสธเมื่อคิวเต็ม
# รับจาก:    ขั้น [2] main.py ส่ง req (GenerateRequest ที่ผ่านขั้น [3] แล้ว) มาที่ enqueue_generate()
# ส่งต่อไป:  ขั้น [5] forge_client.generate_image() เมื่อถึงคิว แล้วส่งผลกลับให้ [2] main.py
# ─────────────────────────────────────────────────────────────────────────────
# queue ส่งไป Forge Neo ยังไง (สรุปสั้น):
#   queue ไม่ได้ส่งไป Forge Neo เอง — แค่ "รอให้ถึงตา" แล้วเรียก generate_image(req) ใน forge_client.py
#   [4.1] เช็คคิวเต็ม (กำลังเจน 1 + รอ 3) → เต็มตอบ 503 ทันที
#   [4.2] นับงานเพิ่ม _pending += 1
#   [4.3] async with _generation_lock → ขอกุญแจ (มีดอกเดียว) ถ้ามีงานอื่นถืออยู่ต้องรอ
#         ระหว่างรอ event loop ยังรับคำขออื่นได้
#   [4.4] ได้กุญแจแล้ว → await generate_image(req) ส่งต่อให้ forge_client.py ([5] เป็นคนยิง HTTP ไป Forge Neo)
#   [4.5] เสร็จหรือ error ก็ตาม → คืนกุญแจ + ลดตัวนับเสมอ งานถัดไปในคิวได้กุญแจต่อ
#
#   main.py ──► queue (รอกุญแจ) ──► forge_client ──HTTP POST──► Forge Neo :7860 (GPU)
#      ◄───────────── รูป base64 ◄──────────────┘
#   มี queue คั่นเพื่อให้ Forge Neo ได้รับงานทีละ 1 งานเท่านั้น GPU จะไม่ต้องรับหลายงานพร้อมกัน
# ─────────────────────────────────────────────────────────────────────────────

import asyncio  # ← ไลบรารี async ของ Python
import logging  # ← ใช้เขียน log
from models import GenerateRequest  # ← รูปแบบคำขอ
from forge_client import generate_image  # ← ฟังก์ชันที่เจนรูปจริง
from config import MAX_QUEUE_SIZE  # ← จำนวนงานที่รอคิวได้สูงสุด

logger = logging.getLogger("uvicorn.error")  # ← ใช้ logger ของ uvicorn ให้ log ขึ้น terminal เดียวกัน

# ค่า 1 หมายถึง "อนุญาตให้มีแค่ 1 งานทำพร้อมกันได้เท่านั้น" งานที่มาทีหลัง
# จะถูกทำให้รอโดยอัตโนมัติที่บรรทัด "async with" ด้านล่าง ไม่ต้องเขียน logic คิวเอง
# [4] กุญแจ 1 ดอก ใช้ร่วมกันทุกคำขอ
_generation_lock = asyncio.Semaphore(1)  # ← กุญแจ 1 ดอก = เจนได้ทีละ 1 งาน คนที่รอจะได้กุญแจตามลำดับที่มาถึง (FIFO)

# จำนวนงานที่อยู่ในระบบตอนนี้ (กำลังทำ 1 + รอคิว) — ใช้ตัดสินว่าคิวเต็มหรือยัง
_pending = 0  # ← ตัวนับงานในระบบ (กำลังเจน + รอคิว) เริ่มที่ 0


class QueueFullError(Exception):  # ← error เมื่อคิวเต็ม (main.py ตอบ 503)
    """โยนเมื่อคิวเต็ม main.py จะแปลงเป็น HTTP 503 ให้ client ลองใหม่ภายหลัง"""
    pass  # ← ไม่มีโค้ดเพิ่ม ใช้แค่ชื่อคลาสบอกชนิดของปัญหา


# [4] ประตูเดียวที่ทุกงานต้องผ่าน — ถูกเรียกจาก [2] main.py
async def enqueue_generate(req: GenerateRequest) -> dict:  # ← ประตูเดียวที่ทุกงานต้องผ่าน
    """
    จุดเดียวที่ main.py เรียกใช้ตอนจะสร้างรูป (แทนที่จะเรียก generate_image()
    ตรงๆ) เพื่อให้งานทุกงานต้องผ่านการ "ต่อคิว" นี้ก่อนเสมอ

    รับข้อมูลมาจากไหน: req (GenerateRequest) ถูกส่งเข้ามาจาก main.py

    ฟังก์ชันนี้ส่งต่อไปไหน: เมื่อถึงคิวของตัวเองแล้ว จะเรียก generate_image()
                           ในไฟล์ forge_client.py ให้ไปทำงานสร้างรูปจริง
                           แล้วส่งผลลัพธ์กลับไปให้ main.py ต่อ
    """
    global _pending  # ← ขอแก้ตัวแปร _pending ที่อยู่นอกฟังก์ชัน
    # [4.1] เช็คคิวเต็ม → ถ้าเต็ม [หยุด] 503 คิวเต็ม (main.py แปลงเป็นรหัส HTTP)
    if _pending >= MAX_QUEUE_SIZE + 1:  # ← มีงานครบแล้วหรือยัง (กำลังเจน 1 + รอ 3 = 4) — ไม่มี await คั่น event loop จึงไม่สลับงานกลางทาง
        raise QueueFullError(f"คิวเต็ม (มีงานรออยู่ {_pending - 1} งาน) กรุณาลองใหม่ภายหลัง")  # ← ปฏิเสธทันที งานนี้ไม่ได้เข้าคิว

    # [4.2] เข้าคิวแล้ว นับเพิ่ม และเขียน log "Task N queued"
    _pending += 1  # ← นับเพิ่ม 1 งาน
    logger.info(f"Task {req.task_id} queued (in system: {_pending})")  # ← log ว่าเข้าคิวแล้ว
    try:  # ← เริ่มบล็อกที่ปิดท้ายด้วย finally (ไม่ว่าเกิดอะไรขึ้น ตัวนับต้องถูกลดคืน)
        # [4.3] รอถึงตา — ถ้ามีงานอื่นกำลังเจน จะรอตรงนี้
        async with _generation_lock:  # ← ขอกุญแจ ถ้ามีงานอื่นถืออยู่จะรอตรงนี้ (รอแบบไม่บล็อก event loop จึงยังรับคำขออื่นได้)
            # โค้ดในบล็อกนี้รับประกันว่ามีแค่ 1 request เท่านั้นที่รันอยู่ในเวลาเดียวกัน
            # request อื่นที่เข้ามาพร้อมกันจะ "ค้างรอ" อยู่ตรงบรรทัด async with ด้านบน
            # โดยอัตโนมัติ จนกว่างานนี้จะทำเสร็จ (ออกจาก block นี้)
            logger.info(f"Task {req.task_id} started")  # ← log ว่าถึงคิวแล้ว เริ่มเจน
            # [4.4] → [5] ถึงตาแล้ว ส่งให้ forge_client.py เจนรูป ผลที่ได้ส่งกลับ [2] main.py
            return await generate_image(req)  # ← เจนรูป แล้วส่งผลกลับให้ main.py
    # [4.5] ออกจากคิว ลดตัวนับคืนเสมอ ทั้งตอนสำเร็จและตอน error
    finally:  # ← ทำเสมอ ทั้งตอนสำเร็จและตอน error
        _pending -= 1  # ← นับลด 1 งาน
